export const medicineBySlug = new Map(medicines.map(m => [m.slug, m]))

/** Аналоги — препараты с тем же действующим веществом. */
export function findAnalogs(slug: string): Medicine[] {
  const source = medicineBySlug.get(slug)
  if (!source) return []
  return medicines.filter(m => m.slug !== slug && m.substance === source.substance)
}

